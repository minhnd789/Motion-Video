/** Tạo clip đồ hoạ với giá trị mặc định của mẫu. Mẫu phủ kín khung lấy đúng kích thước dự án. */
export const makeMotionClip = (
  preset: MotionPreset,
  frame: { width: number; height: number; fps: number },
  patch: Partial<MotionClip> = {},
): MotionClip => {
  const meta = MOTION_PRESETS[preset];
  return {
    id: uid(),
    name: meta.label,
    type: "motion",
    start: 0,
    duration: Math.max(1, Math.round(meta.seconds * frame.fps)),
    ...visualDefaults,
    animIn: { type: meta.full ? "none" : "fade", duration: 8 },
    animOut: { type: meta.full ? "none" : "fade", duration: 8 },
    preset,
    variant: meta.variants ? Object.keys(meta.variants)[0] : "",
    w: meta.full ? frame.width : meta.w,
    h: meta.full ? frame.height : meta.h,
    text: "",
    text2: "",
    items: "",
    value: 0,
    color: "#ffffff",
    color2: "#ffd166",
    color3: "#1d1b26",
    fontFamily: "Be Vietnam Pro",
    src: "",
    ...meta.defaults,
    ...patch,
  };
};
