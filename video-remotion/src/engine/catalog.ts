/** co-san: trình chỉnh sửa đã có từ trước; nang-cap: có một phần, nay bổ sung; moi: mới cài thêm */
export type CatalogStatus = "co-san" | "nang-cap" | "moi";

export type CatalogCtx = { width: number; height: number; fps: number; variant?: string };

type Patch = Partial<TextClip> | Partial<VideoClip> | Partial<ImageClip> | Partial<MotionClip>;

export type CatalogEntry = {
  n: number;
  id: string;
  group: CatalogGroupId;
  en: string;
  vi: string;
  desc: string;
  keywords: string[];
  status: CatalogStatus;
  /** Cách làm trong trình chỉnh sửa (để người dùng tự chỉnh lại) */
  how: string;
  variants?: Record<string, string>;
  /** Loại clip áp dụng được, để hiện cho người dùng */
  applyTo?: string;
  /** Trả về phần sửa cho clip đang chọn, hoặc null nếu loại clip không hợp */
  apply?: (clip: VisualClip, ctx: CatalogCtx) => Patch | null;
  /** Tạo clip mẫu mới */
  sample?: (ctx: CatalogCtx) => Clip;
};

// ---------- Tiện ích tạo mẫu ----------

const anim = (type: AnimType, frames: number, easing?: EasingType): Anim => (easing ? { type, duration: frames, easing } : { type, duration: frames });
const isText = (c: VisualClip): c is TextClip => c.type === "text";
const isMedia = (c: VisualClip): c is VideoClip | ImageClip => c.type === "video" || c.type === "image";

const txt = (ctx: CatalogCtx, patch: Partial<TextClip>) =>
  makeTextClip({
    duration: ctx.fps * 4,
    animIn: anim("none", 12),
    animOut: anim("fade", 10),
    ...patch,
  });

const mo = (preset: MotionPreset, ctx: CatalogCtx, patch: Partial<MotionClip> = {}) =>
  makeMotionClip(preset, ctx, ctx.variant && MOTION_PRESETS[preset].variants?.[ctx.variant] ? { variant: ctx.variant, ...patch } : patch);

const textEffect = (effect: TextClip["textEffect"], extra: Partial<TextClip> = {}) => (c: VisualClip) =>
  isText(c) ? { textEffect: effect, ...extra } : null;

/** Hình tròn mẫu dùng để minh hoạ nguyên lý chuyển động */
const ball = (ctx: CatalogCtx, patch: Partial<MotionClip>) => mo("dot", ctx, { variant: "circle", duration: ctx.fps * 3, ...patch });

/** Giữ kiểu hiệu ứng vào hiện có, nếu chưa có thì dùng `fallback`. */
const keepIn = (c: VisualClip, fallback: AnimType) => (c.animIn.type === "none" ? fallback : c.animIn.type);

